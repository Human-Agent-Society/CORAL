"""Execute the registered visible-champion imitation policy through CORAL."""

from __future__ import annotations

import argparse
import ast
import fcntl
import hashlib
import json
import os
import random
import subprocess
import time
from pathlib import Path
from typing import Any

from initialize_candidate import base_agent_id, initial_candidate

POLICY = "registered_mixed"
STATE_SCHEMA_VERSION = 3
STATE_FILENAME = "scripted-policy-state.json"
TRACE_FILENAME = "scripted-policy.jsonl"
LEADERBOARD_FILENAME = ".scripted-policy-leaderboard.snapshot"
LEADERBOARD_LOCK_FILENAME = ".scripted-policy-leaderboard.lock"
PENDING_VISIBILITY_TIMEOUT = 5.0


def valid_candidate_digest(value: object) -> bool:
    return bool(
        isinstance(value, str)
        and len(value) == 64
        and all(character in "0123456789abcdef" for character in value)
    )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--attempts-per-agent", type=int, required=True)
    parser.add_argument("--visible-agents", type=int, required=True)
    return parser.parse_args()


def literal_candidate(path: Path) -> str:
    tree = ast.parse(path.read_text(), filename=path.name)
    values = [
        node.value.value
        for node in tree.body
        if isinstance(node, (ast.Assign, ast.AnnAssign))
        and isinstance(node.value, ast.Constant)
        and isinstance(node.value.value, str)
    ]
    if len(values) != 1 or len(values[0]) != 512 or set(values[0]) - {"0", "1"}:
        raise ValueError("candidate.py does not contain one 512-bit literal")
    return values[0]


def write_candidate(
    path: Path,
    candidate: str,
    *,
    recovery_nonce: int | None = None,
) -> None:
    rendered = (
        '\"\"\"Candidate generated by the registered scripted policy.\"\"\"\n\n'
        f'CANDIDATE = "{candidate}"\n'
    )
    if recovery_nonce is not None:
        # A killed ``coral eval`` may have committed the candidate without
        # admitting an attempt record.  A comment-only nonce lets recovery
        # submit the identical literal as a new Git commit.
        rendered += f"# Admission recovery nonce: {recovery_nonce}\n"
    path.write_text(rendered)


def attempt_records(attempts_dir: Path) -> list[dict[str, Any]]:
    """Read every visible attempt, including pending and grader-error records."""
    records: dict[str, dict[str, Any]] = {}
    for path in attempts_dir.glob("*.json"):
        try:
            record = json.loads(path.read_text())
        except (OSError, json.JSONDecodeError):
            continue
        commit = record.get("commit_hash")
        if isinstance(commit, str):
            records[commit] = record
    return sorted(records.values(), key=lambda row: (str(row.get("timestamp")), row["commit_hash"]))


def read_attempt_record(
    attempts_dir: Path,
    commit_hash: str,
) -> dict[str, Any] | None:
    path = attempts_dir / f"{commit_hash}.json"
    try:
        record = json.loads(path.read_text())
    except (OSError, json.JSONDecodeError):
        return None
    if not isinstance(record, dict) or record.get("commit_hash") != commit_hash:
        return None
    return record


def finalized_real(record: dict[str, Any] | None) -> bool:
    return bool(
        isinstance(record, dict)
        and record.get("status") != "pending"
        and record.get("metadata", {}).get("budget_class", "real") == "real"
        and isinstance(record.get("score"), (int, float))
    )


def visible_attempts(attempts_dir: Path) -> list[dict[str, Any]]:
    """Return finalized, scored real attempts available in the current topology."""
    return [record for record in attempt_records(attempts_dir) if finalized_real(record)]


def own_attempts(records: list[dict[str, Any]], agent_id: str) -> list[dict[str, Any]]:
    base = base_agent_id(agent_id)
    return [row for row in records if base_agent_id(str(row.get("agent_id", ""))) == base]


def observe_finalized_attempt(
    root: Path,
    agent_id: str,
    state: dict[str, Any],
    record: dict[str, Any],
) -> dict[str, Any]:
    """Durably retain the agent's best finalized attempt across migration."""
    if not finalized_real(record):
        raise RuntimeError("cannot observe a non-finalized scripted attempt")
    if base_agent_id(str(record.get("agent_id", ""))) != base_agent_id(agent_id):
        raise RuntimeError("cannot observe another agent's scripted attempt")
    if record.get("commit_hash") != state.get("last_commit_hash"):
        raise RuntimeError("finalized attempt is not the durable latest commit")
    candidate = {
        "commit_hash": str(record["commit_hash"]),
        "score": float(record["score"]),
        "agent_id": str(record["agent_id"]),
    }
    previous = state.get("best_attempt")
    if isinstance(previous, dict) and (
        float(previous["score"]),
        str(previous["commit_hash"]),
    ) >= (candidate["score"], candidate["commit_hash"]):
        return state
    updated = dict(state)
    updated["best_attempt"] = candidate
    _write_json_atomic(state_path(root), updated)
    return updated


def _leaderboard_payload(attempts_dir: Path) -> dict[str, Any]:
    path = attempts_dir / LEADERBOARD_FILENAME
    try:
        payload = json.loads(path.read_text())
    except (OSError, json.JSONDecodeError):
        return {"schema_version": 1, "entries": {}}
    if (
        not isinstance(payload, dict)
        or payload.get("schema_version") != 1
        or not isinstance(payload.get("entries"), dict)
    ):
        raise RuntimeError("invalid scripted island leaderboard")
    return payload


def visible_leaders(
    attempts_dir: Path,
    publish: dict[str, Any] | None = None,
) -> list[dict[str, Any]]:
    """Return one current-island champion per base agent in constant space.

    Entries whose attempt record moved away during migration are removed under
    a small island-local file lock.  A migrant then republishes its durable
    best attempt in the destination, so the snapshot follows actual attempt
    visibility without scanning the full history on every proposal.
    """
    attempts_dir.mkdir(parents=True, exist_ok=True)
    lock_path = attempts_dir / LEADERBOARD_LOCK_FILENAME
    with lock_path.open("a+") as lock:
        fcntl.flock(lock.fileno(), fcntl.LOCK_EX)
        try:
            payload = _leaderboard_payload(attempts_dir)
            cleaned: dict[str, dict[str, Any]] = {}
            for key, entry in payload["entries"].items():
                if not isinstance(entry, dict):
                    continue
                commit_hash = entry.get("commit_hash")
                if not isinstance(commit_hash, str):
                    continue
                record = read_attempt_record(attempts_dir, commit_hash)
                if not finalized_real(record):
                    continue
                owner = base_agent_id(str(record.get("agent_id", "")))
                if owner != key:
                    continue
                cleaned[owner] = {
                    "commit_hash": commit_hash,
                    "score": float(record["score"]),
                    "agent_id": str(record["agent_id"]),
                }
            if publish is not None:
                commit_hash = str(publish.get("commit_hash", ""))
                record = read_attempt_record(attempts_dir, commit_hash)
                if not finalized_real(record):
                    raise RuntimeError("cannot publish an invisible scripted attempt")
                owner = base_agent_id(str(record.get("agent_id", "")))
                proposed = {
                    "commit_hash": commit_hash,
                    "score": float(record["score"]),
                    "agent_id": str(record["agent_id"]),
                }
                previous = cleaned.get(owner)
                if previous is None or (
                    proposed["score"],
                    proposed["commit_hash"],
                ) > (previous["score"], previous["commit_hash"]):
                    cleaned[owner] = proposed
            updated = {"schema_version": 1, "entries": cleaned}
            _write_json_atomic(attempts_dir / LEADERBOARD_FILENAME, updated)
        finally:
            fcntl.flock(lock.fileno(), fcntl.LOCK_UN)
    return sorted(
        cleaned.values(),
        key=lambda row: (float(row["score"]), str(row["commit_hash"])),
        reverse=True,
    )


def mutation_indices(agent_id: str, local_attempt: int, n: int = 512) -> tuple[int, ...]:
    label = f"threshold-v4-scripted-policy:{base_agent_id(agent_id)}:{local_attempt}"
    seed = int.from_bytes(hashlib.sha256(label.encode()).digest()[:8], "big")
    rng = random.Random(seed)
    draw = rng.random()
    count = 1 if draw < 0.90 else 2 if draw < 0.98 else 4
    return tuple(sorted(rng.sample(range(n), count)))


def initial_title(agent_id: str, local_attempt: int) -> str:
    """Give each agent's initial admission a distinct Git commit message.

    Two agents can legitimately derive the same initial candidate in a shared
    parent tree.  The commit message is part of Git's object identity, so the
    full runtime agent id prevents those otherwise identical admissions from
    colliding in the island-scoped ``attempts/<hash>.json`` queue.
    """
    return f"scripted registered initial candidate agent={agent_id} attempt={local_attempt}"


def proposal_title(
    agent_id: str,
    local_attempt: int,
    parent_hash: str,
    parent_score: float,
    flips: tuple[int, ...],
) -> str:
    """Build an agent-unique title for a registered mutation admission."""
    return (
        f"scripted {POLICY} agent={agent_id}: attempt={local_attempt} "
        f"parent={parent_hash[:12]} score={float(parent_score):.10f} "
        f"flips={','.join(map(str, flips))}"
    )


def run(command: list[str]) -> str:
    result = subprocess.run(command, capture_output=True, text=True)
    output = result.stdout + result.stderr
    print(output, flush=True)
    if result.returncode != 0:
        raise RuntimeError(f"command failed ({result.returncode}): {' '.join(command)}")
    return output


def git_head(root: Path) -> str:
    result = subprocess.run(
        ["git", "rev-parse", "HEAD"],
        cwd=root,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise RuntimeError(f"cannot resolve scripted worktree HEAD: {result.stderr}")
    return result.stdout.strip()


def clear_stale_worktree_index_lock(root: Path) -> bool:
    """Remove this worktree's lock after the prior controller was killed.

    The manager waits for the complete agent process group to exit before it
    restarts a migrated/resynced controller.  A surviving ``index.lock`` is
    therefore an orphan from the interrupted ``git add``/``git commit``, not a
    live writer.  Resolve and scope-check the Git-owned path before unlinking;
    never touch a lock outside this repository's common Git directory.
    """
    lock_result = subprocess.run(
        ["git", "rev-parse", "--git-path", "index.lock"],
        cwd=root,
        capture_output=True,
        text=True,
    )
    common_result = subprocess.run(
        ["git", "rev-parse", "--git-common-dir"],
        cwd=root,
        capture_output=True,
        text=True,
    )
    if lock_result.returncode != 0 or common_result.returncode != 0:
        raise RuntimeError("cannot resolve scripted worktree Git lock path")
    lock = Path(lock_result.stdout.strip())
    if not lock.is_absolute():
        lock = root / lock
    common = Path(common_result.stdout.strip())
    if not common.is_absolute():
        common = root / common
    lock = lock.resolve()
    common = common.resolve()
    try:
        lock.relative_to(common)
    except ValueError as exc:
        raise RuntimeError("scripted worktree index lock escaped Git common dir") from exc
    if not lock.exists():
        return False
    if not lock.is_file():
        raise RuntimeError("scripted worktree index lock is not a regular file")
    lock.unlink()
    print(f"removed stale worktree Git lock: {lock}", flush=True)
    return True


def checkout_visible(root: Path, commit_hash: str) -> bool:
    """Checkout a still-visible attempt, detecting migration TOCTOU races.

    The interactive ``coral checkout`` command intentionally exits zero when
    its target stopped being visible.  That is friendly for an LLM, but a
    registered controller must not silently mutate whatever happened to be in
    its worktree.  Verify the resulting HEAD before deriving a proposal.
    """
    run(["coral", "checkout", commit_hash])
    observed = git_head(root)
    if observed != commit_hash:
        print(
            "visible champion changed during checkout; retrying selection "
            f"(wanted {commit_hash[:12]}, retained {observed[:12]})",
            flush=True,
        )
        return False
    return True


def state_path(root: Path) -> Path:
    return root / ".coral-tmp" / STATE_FILENAME


def trace_path(root: Path) -> Path:
    return root / ".coral-tmp" / TRACE_FILENAME


def _write_json_atomic(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    temporary.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n")
    os.replace(temporary, path)


def initial_state(agent_id: str) -> dict[str, Any]:
    return {
        "schema_version": STATE_SCHEMA_VERSION,
        "base_agent_id": base_agent_id(agent_id),
        "completed_attempts": 0,
        "last_commit_hash": None,
        "best_attempt": None,
        "pending": None,
    }


def load_state(root: Path, agent_id: str) -> dict[str, Any]:
    path = state_path(root)
    if not path.is_file():
        state = initial_state(agent_id)
        _write_json_atomic(path, state)
        return state
    try:
        state = json.loads(path.read_text())
    except (OSError, json.JSONDecodeError) as exc:
        raise RuntimeError(f"invalid scripted policy state: {exc}") from exc
    expected_base = base_agent_id(agent_id)
    if not isinstance(state, dict):
        raise RuntimeError("scripted policy state must be a JSON object")
    if state.get("schema_version") != STATE_SCHEMA_VERSION:
        raise RuntimeError("unsupported scripted policy state schema")
    if state.get("base_agent_id") != expected_base:
        raise RuntimeError("scripted policy state belongs to a different base agent")
    completed = state.get("completed_attempts")
    if not isinstance(completed, int) or completed < 0:
        raise RuntimeError("scripted policy completed_attempts must be non-negative")
    last_commit = state.get("last_commit_hash")
    if (completed == 0 and last_commit is not None) or (
        completed > 0
        and (
            not isinstance(last_commit, str)
            or len(last_commit) != 40
            or any(character not in "0123456789abcdef" for character in last_commit)
        )
    ):
        raise RuntimeError("scripted policy last commit is inconsistent")
    best_attempt = state.get("best_attempt")
    if best_attempt is not None:
        if (
            not isinstance(best_attempt, dict)
            or not isinstance(best_attempt.get("commit_hash"), str)
            or len(best_attempt["commit_hash"]) != 40
            or not isinstance(best_attempt.get("score"), (int, float))
            or base_agent_id(str(best_attempt.get("agent_id", ""))) != expected_base
        ):
            raise RuntimeError("scripted policy best attempt is invalid")
    pending = state.get("pending")
    if pending is not None:
        if not isinstance(pending, dict):
            raise RuntimeError("scripted policy pending state must be an object or null")
        local_attempt = pending.get("local_attempt")
        if local_attempt != completed + 1:
            raise RuntimeError("scripted policy pending attempt is not sequence-contiguous")
        trace = pending.get("trace")
        if not isinstance(pending.get("title"), str) or not isinstance(trace, dict):
            raise RuntimeError("scripted policy pending state is incomplete")
        if not valid_candidate_digest(trace.get("candidate_sha256")):
            raise RuntimeError("scripted policy pending candidate hash is invalid")
        recovery_submissions = pending.get("recovery_submissions")
        if not isinstance(recovery_submissions, int) or recovery_submissions < 0:
            raise RuntimeError("scripted policy pending recovery count is invalid")
        commit_hash = pending.get("commit_hash")
        if commit_hash is not None and (
            not isinstance(commit_hash, str)
            or len(commit_hash) != 40
            or any(character not in "0123456789abcdef" for character in commit_hash)
        ):
            raise RuntimeError("scripted policy pending commit hash is invalid")
    return state


def reserve_submission(
    root: Path,
    state: dict[str, Any],
    *,
    title: str,
    trace: dict[str, Any],
) -> dict[str, Any]:
    if state.get("pending") is not None:
        raise RuntimeError("cannot reserve a second scripted policy submission")
    local_attempt = trace.get("local_attempt")
    if local_attempt != int(state["completed_attempts"]) + 1:
        raise RuntimeError("scripted policy submission is not sequence-contiguous")
    if not valid_candidate_digest(trace.get("candidate_sha256")):
        raise RuntimeError("scripted policy submission candidate hash is invalid")
    updated = dict(state)
    updated["pending"] = {
        "local_attempt": local_attempt,
        "title": title,
        "trace": trace,
        "recovery_submissions": 0,
        "commit_hash": None,
    }
    _write_json_atomic(state_path(root), updated)
    return updated


def record_pending_commit(
    root: Path,
    state: dict[str, Any],
    commit_hash: str,
) -> dict[str, Any]:
    pending = state.get("pending")
    if not isinstance(pending, dict):
        raise RuntimeError("cannot record a commit without a pending reservation")
    if (
        len(commit_hash) != 40
        or any(character not in "0123456789abcdef" for character in commit_hash)
    ):
        raise RuntimeError("scripted admission produced an invalid commit hash")
    updated_pending = dict(pending)
    updated_pending["commit_hash"] = commit_hash
    updated = dict(state)
    updated["pending"] = updated_pending
    _write_json_atomic(state_path(root), updated)
    return updated


def _trace_contains(root: Path, agent_id: str, local_attempt: int) -> bool:
    path = trace_path(root)
    if not path.is_file():
        return False
    for line in path.read_text().splitlines():
        try:
            record = json.loads(line)
        except json.JSONDecodeError:
            continue
        if (
            base_agent_id(str(record.get("agent_id", ""))) == base_agent_id(agent_id)
            and record.get("local_attempt") == local_attempt
        ):
            return True
    return False


def append_trace(root: Path, payload: dict[str, Any]) -> None:
    trace = trace_path(root)
    trace.parent.mkdir(parents=True, exist_ok=True)
    with trace.open("a") as handle:
        handle.write(json.dumps(payload, sort_keys=True) + "\n")


def reconcile_pending(
    root: Path,
    agent_id: str,
    state: dict[str, Any],
    records: list[dict[str, Any]],
) -> dict[str, Any]:
    """Finalize a reserved local sequence number once its attempt is admitted.

    Migration moves an agent's attempt records with the agent.  Matching on the
    unique title therefore works before and after the shared attempts symlink is
    repointed, including while the grader record is still pending.
    """
    pending = state.get("pending")
    if not isinstance(pending, dict):
        return state
    matches = [
        record
        for record in own_attempts(records, agent_id)
        if record.get("title") == pending["title"]
    ]
    if not matches:
        return state
    if len(matches) != 1:
        raise RuntimeError("scripted policy submission title is not unique")
    record = matches[0]
    budget_class = record.get("metadata", {}).get("budget_class", "real")
    if budget_class != "real":
        raise RuntimeError(
            f"scripted policy submission became non-real ({budget_class})"
        )
    local_attempt = int(pending["local_attempt"])
    payload = dict(pending["trace"])
    payload["commit_hash"] = record["commit_hash"]
    payload["admission_status"] = "queued"
    payload["admission_recovery_submissions"] = pending["recovery_submissions"]
    if not _trace_contains(root, agent_id, local_attempt):
        append_trace(root, payload)
    updated = dict(state)
    updated["completed_attempts"] = local_attempt
    updated["last_commit_hash"] = record["commit_hash"]
    updated["pending"] = None
    _write_json_atomic(state_path(root), updated)
    return updated


def submit_reserved(
    root: Path,
    agent_id: str,
    attempts_dir: Path,
    state: dict[str, Any],
    *,
    title: str,
    trace: dict[str, Any],
) -> dict[str, Any]:
    state = reserve_submission(root, state, title=title, trace=trace)
    run(["coral", "eval", "--no-wait", "-m", title])
    # The manager may resync this worktree immediately after admission, so
    # HEAD is no longer authoritative once `coral eval` returns. Reconcile
    # the unique title in this agent's visible attempt records instead.
    state = wait_for_pending(root, agent_id, attempts_dir, state)
    if state.get("pending") is not None:
        raise RuntimeError(
            "new scripted submission returned without an attempt record; "
            "restart the controller to run hash-checked admission recovery"
        )
    return state


def wait_for_pending(
    root: Path,
    agent_id: str,
    attempts_dir: Path,
    state: dict[str, Any],
    *,
    timeout: float = PENDING_VISIBILITY_TIMEOUT,
) -> dict[str, Any]:
    """Wait briefly for a synchronously admitted attempt record to appear.

    The reservation remains durable on timeout.  Callers decide whether an
    absent record is an error or whether to invoke the hash-checked recovery
    path below.
    """
    deadline = time.monotonic() + timeout
    while state.get("pending") is not None:
        pending = state["pending"]
        commit_hash = pending.get("commit_hash")
        if isinstance(commit_hash, str):
            record = read_attempt_record(attempts_dir, commit_hash)
            records = [record] if record is not None else []
        else:
            # Post-eval HEAD can be changed by a manager resync. Find the
            # admitted record by its unique title and owner instead; the same
            # scan also recovers a process killed before reconciliation.
            records = attempt_records(attempts_dir)
        state = reconcile_pending(root, agent_id, state, records)
        if state.get("pending") is None:
            return state
        if time.monotonic() >= deadline:
            break
        time.sleep(0.05)
    return state


def recover_pending(
    root: Path,
    agent_id: str,
    attempts_dir: Path,
    state: dict[str, Any],
    *,
    visibility_timeout: float = PENDING_VISIBILITY_TIMEOUT,
) -> dict[str, Any]:
    """Recover a reservation killed before ``submit_eval`` admission.

    ``submit_eval`` writes the attempt record synchronously before returning.
    Migration waits for the killed controller process to exit and then moves
    all of that agent's attempt records to its destination island.  Therefore,
    after a visibility grace period, a missing title means admission did not
    finish.  Recovery is allowed only when the current literal hashes to the
    exact candidate stored in the durable reservation.

    Each retry adds a comment-only nonce.  This preserves the experimental
    candidate while guaranteeing a Git diff even when a previous killed retry
    left an orphan commit but no attempt record.
    """
    state = wait_for_pending(
        root,
        agent_id,
        attempts_dir,
        state,
        timeout=visibility_timeout,
    )
    pending = state.get("pending")
    if not isinstance(pending, dict):
        return state

    trace = pending["trace"]
    expected_digest = str(trace["candidate_sha256"])
    candidate_path = root / "candidate.py"
    candidate = literal_candidate(candidate_path)
    actual_digest = hashlib.sha256(candidate.encode()).hexdigest()
    if actual_digest != expected_digest:
        raise RuntimeError(
            "reserved scripted candidate hash does not match candidate.py; "
            "refusing admission recovery"
        )

    clear_stale_worktree_index_lock(root)
    recovery_submissions = int(pending["recovery_submissions"]) + 1
    updated_pending = dict(pending)
    updated_pending["recovery_submissions"] = recovery_submissions
    updated = dict(state)
    updated["pending"] = updated_pending
    _write_json_atomic(state_path(root), updated)

    write_candidate(
        candidate_path,
        candidate,
        recovery_nonce=recovery_submissions,
    )
    run(["coral", "eval", "--no-wait", "-m", str(pending["title"])])
    updated = wait_for_pending(
        root,
        agent_id,
        attempts_dir,
        updated,
        timeout=visibility_timeout,
    )
    if updated.get("pending") is not None:
        raise RuntimeError(
            "recovered scripted submission returned without an attempt record"
        )
    return updated


def submit_initial(
    root: Path,
    agent_id: str,
    attempts_dir: Path,
    state: dict[str, Any],
) -> dict[str, Any]:
    candidate = initial_candidate(agent_id)
    write_candidate(root / "candidate.py", candidate)
    local_attempt = 1
    title = initial_title(agent_id, local_attempt)
    trace = {
        "type": "initial",
        "selected_at": time.time(),
        "agent_id": agent_id,
        "local_attempt": local_attempt,
        "candidate_sha256": hashlib.sha256(candidate.encode()).hexdigest(),
        "island_id": (root / ".coral_island").read_text().strip()
        if (root / ".coral_island").is_file()
        else None,
    }
    return submit_reserved(
        root,
        agent_id,
        attempts_dir,
        state,
        title=title,
        trace=trace,
    )


def submit_mutation(
    root: Path,
    agent_id: str,
    attempts_dir: Path,
    state: dict[str, Any],
    records: list[dict[str, Any]],
) -> dict[str, Any]:
    ranked = sorted(
        records,
        key=lambda row: (float(row["score"]), row["commit_hash"]),
        reverse=True,
    )
    leader = ranked[0]
    if not checkout_visible(root, leader["commit_hash"]):
        return state
    parent = literal_candidate(root / "candidate.py")
    local_attempt = int(state["completed_attempts"]) + 1
    flips = mutation_indices(agent_id, local_attempt - 1)
    bits = list(parent)
    for index in flips:
        bits[index] = "0" if bits[index] == "1" else "1"
    candidate = "".join(bits)
    write_candidate(root / "candidate.py", candidate)
    selected_at = time.time()
    title = proposal_title(
        agent_id,
        local_attempt,
        str(leader["commit_hash"]),
        float(leader["score"]),
        flips,
    )
    trace = {
        "type": "proposal",
        "selected_at": selected_at,
        "agent_id": agent_id,
        "local_attempt": local_attempt,
        "parent_hash": leader["commit_hash"],
        "parent_score": leader["score"],
        "visible_champions": len(records),
        "visible_top": [
            {"commit_hash": row["commit_hash"], "score": row["score"]}
            for row in ranked[:5]
        ],
        "island_id": (root / ".coral_island").read_text().strip()
        if (root / ".coral_island").is_file()
        else None,
        "flips": list(flips),
        "policy": POLICY,
        "candidate_sha256": hashlib.sha256(candidate.encode()).hexdigest(),
    }
    return submit_reserved(
        root,
        agent_id,
        attempts_dir,
        state,
        title=title,
        trace=trace,
    )


def main() -> None:
    args = parse_args()
    if args.attempts_per_agent < 1 or args.visible_agents < 1:
        raise SystemExit("attempt and visible-agent counts must be positive")
    root = Path(__file__).resolve().parent
    agent_id = (root / ".coral_agent_id").read_text().strip()
    attempts_dir = root / ".scripted" / "attempts"
    coral_dir = Path((root / ".coral_dir").read_text().strip())
    auto_stop = coral_dir / "public" / "auto_stop.json"
    state = load_state(root, agent_id)
    if state.get("pending") is not None:
        state = recover_pending(root, agent_id, attempts_dir, state)
    while not auto_stop.is_file():
        completed = int(state["completed_attempts"])
        if completed == 0:
            state = submit_initial(root, agent_id, attempts_dir, state)
            continue
        last_commit = str(state["last_commit_hash"])
        latest = read_attempt_record(attempts_dir, last_commit)
        if latest is None or latest.get("status") == "pending":
            time.sleep(0.2)
            continue
        if not finalized_real(latest):
            raise RuntimeError("scripted policy latest attempt did not finalize as real")
        state = observe_finalized_attempt(root, agent_id, state, latest)
        leaders = visible_leaders(attempts_dir, publish=state["best_attempt"])
        if completed >= args.attempts_per_agent:
            time.sleep(0.2)
            continue
        if len(leaders) < args.visible_agents:
            time.sleep(0.2)
            continue
        state = submit_mutation(root, agent_id, attempts_dir, state, leaders)
    print("scripted policy observed run auto-stop", flush=True)


if __name__ == "__main__":
    main()
